import pygame

# ------------------------------------------------------------
# Initialize Pygame
# ------------------------------------------------------------
pygame.init()

# ------------------------------------------------------------
# Window Settings
# ------------------------------------------------------------
WIDTH = 800
HEIGHT = 600

screen = pygame.display.set_mode((WIDTH, HEIGHT))

pygame.display.set_caption("My First AI Game Window")

# ------------------------------------------------------------
# Colors
# ------------------------------------------------------------
BACKGROUND_COLOR = (30, 144, 255)   # Dodger Blue
WHITE = (255, 255, 255)
BLACK = (0, 0, 0)

# ------------------------------------------------------------
# Font Settings
# ------------------------------------------------------------
font = pygame.font.SysFont("arial", 40)

# Create text
title_text = font.render("Welcome to AI Game Development!", True, WHITE)

# ------------------------------------------------------------
# Clock for FPS Control
# ------------------------------------------------------------
clock = pygame.time.Clock()

# ------------------------------------------------------------
# Game Loop
# ------------------------------------------------------------
running = True

while running:

    # --------------------------------------------------------
    # Check Events
    # --------------------------------------------------------
    for event in pygame.event.get():

        # If player clicks the close button
        if event.type == pygame.QUIT:
            running = False

    # --------------------------------------------------------
    # Fill Background
    # --------------------------------------------------------
    screen.fill(BACKGROUND_COLOR)

    # --------------------------------------------------------
    # Draw Text
    # --------------------------------------------------------
    screen.blit(title_text, (120, 250))

    # --------------------------------------------------------
    # Update Display
    # --------------------------------------------------------
    pygame.display.update()

    # --------------------------------------------------------
    # Control FPS
    # --------------------------------------------------------
    clock.tick(60)

# ------------------------------------------------------------
# Quit Pygame
# ------------------------------------------------------------
pygame.quit()
